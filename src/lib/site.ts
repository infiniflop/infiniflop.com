type PageMetadataInput = {
  /** Route path, e.g. "/" or "/about". Resolved against metadataBase. */
  path: string;
  /** Page title. Omit on the home page to use the site name alone. */
  title?: string;
  description?: string;
};

/**
 * Metadata for one route.
 *
 * Next.js replaces `openGraph` and `twitter` objects wholesale when a page
 * defines them (nested fields are not merged with the layout), so every page
 * builds its full set here. The share image comes from the colocated
 * `opengraph-image` and `twitter-image` files in the page's own folder, which
 * Next.js links with a content-hashed URL. The root page uses the files in
 * `src/app`. A page in a nested folder (e.g. `src/app/about/`) must add its own
 * `opengraph-image.tsx` and `twitter-image.tsx` next to its `page.tsx`: the
 * root files do not attach to nested pages once a page sets its own `openGraph`.
 * Copy the root files to reuse the default card, or render a distinct one.
 */
export function pageMetadata({
  path,
  title,
  description = SITE_DESCRIPTION,
}: PageMetadataInput): Metadata {
  const socialTitle = title ? `${title} | ${SITE_NAME}` : SITE_NAME;

  return {
    ...(title ? { title } : {}),
    description,
    alternates: { canonical: path },
    // Explicit so every indexable page states its policy. Not set in the
    // layout: Next.js adds its own noindex to the 404 page, and a layout-level
    // index tag would contradict it.
    robots: {
      index: true,
      follow: true,
      googleBot: {
        index: true,
        follow: true,
        "max-image-preview": "large",
        "max-snippet": -1,
        "max-video-preview": -1,
      },
    },
    openGraph: {
      type: "website",
      url: path,
      siteName: SITE_NAME,
      locale: SITE_LOCALE,
      title: socialTitle,
      description,
    },
    twitter: {
      card: "summary_large_image",
      site: TWITTER_SITE,
      title: socialTitle,
      description,
    },
  };
}
