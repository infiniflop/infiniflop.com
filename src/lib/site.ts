/**
 * Absolute production URL for a route path. The root is the bare origin, which
 * is the form Next.js emits for canonical and og:url, so every URL we publish
 * (canonical, sitemap, structured data) is spelled identically.
 */
export function absoluteUrl(path: string): string {
  return path === "/" ? SITE_URL : `${SITE_URL}${path}`;
}

